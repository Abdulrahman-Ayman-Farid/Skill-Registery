import 'dotenv/config';
import { eq } from 'drizzle-orm';
import { db } from './index';
import { users, skills } from './schema';
import { STARTER_SKILLS } from '../data/starterSkills';
import { DEFAULT_USERS } from '../services/storageService';

async function main() {
  if (!process.env.DATABASE_URL) {
    console.error('DATABASE_URL is missing from the environment (.env). Aborting seed.');
    process.exit(1);
  }

  // 1. Upsert default users (idempotent: conflict on id / unique email does nothing)
  await db
    .insert(users)
    .values(
      DEFAULT_USERS.map((u) => ({
        name: u.name,
        email: u.email,
        role: u.role,
        avatarUrl: u.avatarUrl,
      })),
    )
    .onConflictDoNothing();
  console.log(`Users: ensured ${DEFAULT_USERS.length} default user(s).`);

  // 2. Resolve the actual DB id of the first default user
  const [owner] = await db
    .select()
    .from(users)
    .where(eq(users.email, DEFAULT_USERS[0].email))
    .limit(1);

  if (!owner) {
    console.error('Default user not found in database after upsert. Aborting.');
    process.exit(1);
  }

  // 3. Upsert starter skills linked to that user.
  // Starter skill ids are not UUIDs, so ids are generated by defaultRandom;
  // idempotency is achieved by skipping skills that already exist for this user
  // with the same name.
  const existing = await db
    .select({ name: skills.name })
    .from(skills)
    .where(eq(skills.userId, owner.id));
  const existingNames = new Set(existing.map((s) => s.name));

  let inserted = 0;
  let skipped = 0;
  for (const skill of STARTER_SKILLS) {
    if (existingNames.has(skill.name)) {
      skipped++;
      continue;
    }
    await db
      .insert(skills)
      .values({
        userId: owner.id,
        name: skill.name,
        description: skill.description,
        category: skill.category,
        executionType: skill.executionType,
        status: skill.status,
        version: skill.version,
        inputSchema: skill.inputSchema,
        outputSchema: skill.outputSchema,
        config: skill.config ?? {},
        tags: skill.tags ?? [],
        dependencies: skill.dependencies ?? [],
        explanation: skill.explanation,
      })
      .onConflictDoNothing();
    inserted++;
  }
  console.log(`Skills: inserted ${inserted}, skipped ${skipped} (already present).`);
}

main()
  .then(() => {
    console.log('Seed completed successfully.');
    return db.$client.end();
  })
  .then(() => process.exit(0))
  .catch(async (err) => {
    console.error('Seed failed:', err);
    try {
      await db.$client.end();
    } catch {
      // ignore close errors during failure path
    }
    process.exit(1);
  });
